################################### LOGGER #####################################

class Logger:
    """Handles logging to file and console"""
    
    def __init__(self, log_path: Path, verbose: bool = True):
        self.log_path = log_path
        self.verbose = verbose
        self.log_file = open(log_path, 'w')
        self.error_count = 0
        self.warning_count = 0
        self.fatal_error = False
        self.closed = False
        
    def info(self, message: str):
        """Log INFO level message"""
        if not self.closed:
            self.log_file.write(f"INFO: {message}\n")
            self.log_file.flush()
        
    def warning(self, message: str):
        """Log WARNING level message"""
        self.warning_count += 1
        if not self.closed:
            self.log_file.write(f"WARNING: {message}\n")
            self.log_file.flush()
        if self.verbose:
            print(f"WARNING: {message}", file=sys.stderr)
    
    def error(self, message: str, fatal: bool = False):
        """Log ERROR level message"""
        self.error_count += 1
        if fatal:
            self.fatal_error = True
        if not self.closed:
            self.log_file.write(f"ERROR: {message}\n")
            self.log_file.flush()
        if self.verbose:
            print(f"ERROR: {message}", file=sys.stderr)
    
    def close(self):
        """Close log file and print summary"""
        if self.closed:
            return
        summary = f"\nSummary: {self.error_count} errors, {self.warning_count} warnings"
        self.info(summary)
        if self.verbose:
            print(summary)
        self.log_file.close()
        self.closed = True

############################ FILE TYPE DETECTOR ################################

class FileTypeDetector:
    """Detects type of include or Fortran source files"""
    
    ACG_WARNING = "W  A  R  N  I  N  G"
    
    @staticmethod
    def detect(filepath: Path, logger: Logger) -> FileType:
        """Detect file type by examining contents"""
        try:
            with open(filepath, 'r') as f:
                content = f.read()
            
            # Check for Fortran source file
            if filepath.suffix.upper() in ['.F90', '.F', '.F03']:
                return FileType.FORTRAN_SOURCE
            
            # Check for specific patterns
            if 'real' in content.lower() and 'pointer' in content.lower() and 'dimension' in content.lower():
                return FileType.DECLARE_POINTER
            elif 'MAPL_GetPointer' in content:
                return FileType.GET_POINTER
            elif 'MAPL_AddImportSpec' in content:
                return FileType.ADD_IMPORT
            elif 'MAPL_AddExportSpec' in content:
                return FileType.ADD_EXPORT
            elif 'MAPL_AddInternalSpec' in content:
                return FileType.ADD_INTERNAL
            else:
                return FileType.UNKNOWN
                
        except Exception as e:
            logger.error(f"Error reading file {filepath}: {e}")
            return FileType.UNKNOWN

######################## DECLARE POINTER PARSER ################################

class DeclarePointerParser:
    """Parses declare pointer include files"""
    
    POINTER_PATTERN = re.compile(
        r'^\s*real(?:\(kind=(\d+)\))?,\s*pointer,\s*dimension\(([:\,]+)\)\s*::\s*(\w+)',
        re.IGNORECASE
    )
    
    def __init__(self, logger: Logger):
        self.logger = logger
    
    def parse(self, filepath: Path) -> Dict[str, Dict]:
        """
        Parse declare pointer file
        
        Returns: {
            'VARNAME': {
                'rank': 3,
                'precision': 8  # optional
            },
            ...
        }
        """
        result = {}
        
        try:
            with open(filepath, 'r') as f:
                for line_num, line in enumerate(f, 1):
                    match = self.POINTER_PATTERN.match(line)
                    if match:
                        precision_str, dimension_str, varname = match.groups()
                        
                        # Compute rank from dimension string (count colons + 1)
                        rank = dimension_str.count(':')
                        
                        field_data = {'rank': rank}
                        if precision_str:
                            field_data['precision'] = int(precision_str)
                        
                        result[varname] = field_data
                        self.logger.info(f"DeclarePointer: {varname} rank={rank}")
                        
        except Exception as e:
            self.logger.error(f"Error parsing DeclarePointer file {filepath}: {e}")
        
        return result

########################## GET POINTER PARSER ##################################

class GetPointerParser:
    """Parses get pointer include files"""
    
    GETPOINTER_PATTERN = re.compile(
        r'call\s+MAPL_GetPointer\s*\(\s*(\w+)\s*,\s*(\w+)\s*,\s*[\'"](\w+)[\'"]',
        re.IGNORECASE
    )
    
    ALLOC_PATTERN = re.compile(r'alloc\s*=\s*(\.true\.|\.false\.)', re.IGNORECASE)
    
    IF_PATTERN = re.compile(r'^\s*if\s*\((.*?)\)\s*then', re.IGNORECASE)
    ENDIF_PATTERN = re.compile(r'^\s*endif', re.IGNORECASE)
    
    def __init__(self, logger: Logger):
        self.logger = logger
    
    def parse(self, filepath: Path) -> Dict[Tuple[str, str], Dict]:
        """
        Parse get pointer file
        
        Returns: {
            ('NAME', 'import'): {
                'category': 'import',
                'varname': 'varname',
                'condition': 'trim(VAR) == "VALUE"',  # optional
                'alloc': True  # optional
            },
            ...
        }
        Note: Keys are tuples of (name, category) to handle fields in multiple categories
        """
        result = {}
        current_condition = None
        condition_stack = []
        
        try:
            with open(filepath, 'r') as f:
                for line_num, line in enumerate(f, 1):
                    # Check for if statement
                    if_match = self.IF_PATTERN.match(line)
                    if if_match:
                        condition = if_match.group(1).strip()
                        condition_stack.append(condition)
                        current_condition = condition
                        continue
                    
                    # Check for endif
                    if self.ENDIF_PATTERN.match(line):
                        if condition_stack:
                            condition_stack.pop()
                        current_condition = condition_stack[-1] if condition_stack else None
                        continue
                    
                    # Check for MAPL_GetPointer call
                    match = self.GETPOINTER_PATTERN.search(line)
                    if match:
                        category_var, varname, name = match.groups()
                        
                        # Determine category from variable name
                        category = category_var.lower()
                        
                        field_data = {
                            'category': category,
                            'varname': varname
                        }
                        
                        if current_condition:
                            field_data['condition'] = current_condition
                        
                        # Check for alloc parameter
                        alloc_match = self.ALLOC_PATTERN.search(line)
                        if alloc_match:
                            alloc_value = alloc_match.group(1).lower()
                            field_data['alloc'] = (alloc_value == '.true.')
                        
                        # Use compound key (name, category) to handle duplicates
                        key = (name, category)
                        result[key] = field_data
                        self.logger.info(f"GetPointer: {name} category={category}")
                        
        except Exception as e:
            self.logger.error(f"Error parsing GetPointer file {filepath}: {e}")
        
        return result

