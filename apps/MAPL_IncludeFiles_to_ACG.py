class AddSpecParser:
    """Parses add spec include files (import/export/internal)"""
    
    ADDSPEC_START = re.compile(
        r'call\s+MAPL_Add(Import|Export|Internal)Spec\s*\(\s*gc\s*,',
        re.IGNORECASE
    )
    
    PARAM_PATTERN = re.compile(r'(\w+)\s*=\s*([^,&]+)')
    
    IF_PATTERN = re.compile(r'^\s*if\s*\((.*?)\)\s*then', re.IGNORECASE)
    ENDIF_PATTERN = re.compile(r'^\s*endif', re.IGNORECASE)
    
    def __init__(self, logger: Logger):
        self.logger = logger
    
    def parse(self, filepath: Path, category: Category) -> List[Dict]:
        """
        Parse add spec file
        
        Returns list of field dictionaries
        """
        result = []
        current_condition = None
        condition_stack = []
        
        try:
            with open(filepath, 'r') as f:
                lines = f.readlines()
            
            i = 0
            while i < len(lines):
                line = lines[i]
                
                # Check for if statement
                if_match = self.IF_PATTERN.match(line)
                if if_match:
                    condition = if_match.group(1).strip()
                    condition_stack.append(condition)
                    current_condition = condition
                    i += 1
                    continue
                
                # Check for endif
                if self.ENDIF_PATTERN.match(line):
                    if condition_stack:
                        condition_stack.pop()
                    current_condition = condition_stack[-1] if condition_stack else None
                    i += 1
                    continue
                
                # Check for AddSpec call
                if self.ADDSPEC_START.search(line):
                    # Accumulate the complete call
                    call_lines = [line]
                    i += 1
                    while i < len(lines):
                        call_lines.append(lines[i])
                        if '_RC)' in lines[i]:
                            break
                        i += 1
                    
                    # Parse the complete call
                    field = self.parse_addspec_call(call_lines, current_condition, category)
                    if field:
                        result.append(field)
                        self.logger.info(f"AddSpec: {field.get('NAME', 'UNKNOWN')} in {category.value}")
                    
                    i += 1
                else:
                    i += 1
                    
        except Exception as e:
            self.logger.error(f"Error parsing AddSpec file {filepath}: {e}")
        
        return result
    
    def parse_addspec_call(self, call_lines: List[str], condition: Optional[str], category: Category) -> Optional[Dict]:
        """Parse a single AddSpec call"""
        # Join lines and remove continuation characters
        call_text = ' '.join(call_lines)
        call_text = call_text.replace('&', ' ')
        
        # Extract parameters
        field = {}
        
        if condition:
            field['COND'] = condition
        
        # Find all parameter=value pairs
        for match in self.PARAM_PATTERN.finditer(call_text):
            param_name = match.group(1).strip().lower()
            param_value = match.group(2).strip()
            
            # Skip special parameters
            if param_name in ['gc', '_rc']:
                continue
            
            # Map parameter name to column name
            column_name = param_to_column_name(param_name)
            
            # Process value
            value = self.process_value(param_value, column_name)
            if value:
                field[column_name] = value
        
        return field if field else None
    
    def process_value(self, value: str, column_name: str) -> str:
        """Process parameter value - unmangle names, map constants, clean up"""
        value = value.strip()
        
        # Remove trailing commas and parentheses
        value = value.rstrip(',)')
        value = value.strip()
        
        # Map MAPL constants
        if column_name == 'DIMS':
            for mapl_const, abbrev in DIMS_REVERSE_MAP.items():
                if mapl_const in value:
                    return abbrev
        elif column_name == 'VLOC':
            for mapl_const, abbrev in VLOC_REVERSE_MAP.items():
                if mapl_const in value:
                    return abbrev
        elif column_name == 'RESTART':
            for mapl_const, abbrev in RESTART_REVERSE_MAP.items():
                if mapl_const in value:
                    return abbrev
        
        # Unmangle names (handle Fortran string concatenation)
        if column_name in ['NAME', 'LONG_NAME', 'FRIENDLYTO']:
            value = self.unmangle_name(value)
        
        # Remove quotes/apostrophes
        if value.startswith("'") and value.endswith("'"):
            value = value[1:-1]
        elif value.startswith('"') and value.endswith('"'):
            value = value[1:-1]
        
        # Handle arrays - remove brackets
        if value.startswith('[') and value.endswith(']'):
            value = value[1:-1]
            value = value.strip()
        
        # Handle logical values
        if value.lower() in ['.true.', '.false.']:
            return 'T' if value.lower() == '.true.' else 'F'
        
        return value
    
    def unmangle_name(self, name_str: str) -> str:
        """
        Reverse name mangling:
        'ZLE' -> ZLE
        'PREFIX'//trim(comp_name)//'SUFFIX' -> *SUFFIX
        """
        # Remove outer quotes first
        if name_str.startswith("'") and name_str.endswith("'"):
            name_str = name_str[1:-1]
        elif name_str.startswith('"') and name_str.endswith('"'):
            name_str = name_str[1:-1]
        
        # Check for concatenation pattern
        if '//' in name_str:
            # Pattern: PREFIX//trim(comp_name)//SUFFIX or variations
            # Look for the suffix after the last //
            parts = name_str.split('//')
            if len(parts) > 1:
                # Get the last part (suffix)
                suffix = parts[-1].strip().strip("'\"")
                if suffix:
                    return '*' + suffix
                # If no suffix, try to get prefix
                prefix = parts[0].strip().strip("'\"")
                if prefix:
                    return prefix + '*'
        
        return name_str

###################### COMPONENT NAME EXTRACTOR ################################

class ComponentNameExtractor:
    """Extracts component name from various sources"""
    
    FILENAME_PATTERNS = [
        re.compile(r'^(\w+)_Import', re.IGNORECASE),
        re.compile(r'^(\w+)_Export', re.IGNORECASE),
        re.compile(r'^(\w+)_Internal', re.IGNORECASE),
        re.compile(r'^(\w+)_DeclarePointer', re.IGNORECASE),
        re.compile(r'^(\w+)_GetPointer', re.IGNORECASE),
    ]
    
    def __init__(self, logger: Logger):
        self.logger = logger
    
    def extract(self, cli_component: Optional[str], file_paths: List[Path]) -> str:
        """Extract component name with priority and cross-checking"""
        extracted_names = set()
        
        # Extract from filenames
        for path in file_paths:
            name = self.extract_from_filename(path)
            if name:
                extracted_names.add(name)
        
        # Determine final component name
        if cli_component:
            # CLI component is authoritative
            if extracted_names and cli_component not in extracted_names:
                self.logger.warning(
                    f"Component name from CLI '{cli_component}' differs from extracted names: {extracted_names}"
                )
            return cli_component
        
        elif len(extracted_names) == 1:
            # Single consistent name found
            component = list(extracted_names)[0]
            self.logger.info(f"Component name extracted: {component}")
            return component
        
        elif len(extracted_names) > 1:
            # Multiple different names found
            self.logger.warning(
                f"Multiple component names found: {extracted_names}. Using first one."
            )
            return sorted(extracted_names)[0]
        
        else:
            # No name found
            self.logger.error("Could not extract component name from filenames")
            return "UNKNOWN"
    
    def extract_from_filename(self, path: Path) -> Optional[str]:
        """Extract component name from filename using patterns"""
        stem = path.stem
        for pattern in self.FILENAME_PATTERNS:
            match = pattern.match(stem)
            if match:
                return match.group(1)
        return None

