class FieldDataMerger:
    """Merges field data from different sources"""
    
    def __init__(self, logger: Logger):
        self.logger = logger
    
    def merge(self, 
              addspec_data: Dict[Category, List[Dict]],
              declare_data: Dict[str, Dict],
              getpointer_data: Dict[Tuple[str, str], Dict]) -> Dict[Category, List[Dict]]:
        """Merge data from all sources"""
        
        merged_data = {}
        
        # Track which fields we've seen in addspec (authoritative)
        addspec_fields = set()
        
        for category, fields in addspec_data.items():
            if not fields:
                continue
            
            merged_fields = []
            
            for field in fields:
                name = field.get('NAME')
                if not name:
                    self.logger.error(f"Field in {category.value} missing NAME")
                    continue
                
                addspec_fields.add((name, category.value.lower()))
                
                # Compute expected rank from DIMS and UNGRIDDED
                dims = field.get('DIMS')
                ungridded = field.get('UNGRIDDED')
                if dims:
                    expected_rank = self.compute_rank(dims, ungridded)
                    
                    # Cross-check with DeclarePointer
                    if name in declare_data:
                        actual_rank = declare_data[name]['rank']
                        if actual_rank != expected_rank:
                            self.logger.error(
                                f"Rank mismatch for {name}: DeclarePointer={actual_rank}, "
                                f"computed from DIMS+UNGRIDDED={expected_rank}"
                            )
                        # Add precision if available
                        if 'precision' in declare_data[name]:
                            field['PRECISION'] = str(declare_data[name]['precision'])
                    else:
                        self.logger.warning(f"Field {name} not found in DeclarePointer file")
                
                # Cross-check with GetPointer using compound key
                gp_key = (name, category.value.lower())
                if gp_key in getpointer_data:
                    gp_category = getpointer_data[gp_key]['category']
                    expected_category = category.value.lower()
                    
                    if gp_category != expected_category:
                        self.logger.error(
                            f"Category mismatch for {name}: GetPointer={gp_category}, "
                            f"AddSpec={expected_category}"
                        )
                    
                    # Check condition consistency
                    gp_condition = getpointer_data[gp_key].get('condition')
                    addspec_condition = field.get('COND')
                    
                    if gp_condition and addspec_condition:
                        if gp_condition != addspec_condition:
                            self.logger.warning(
                                f"Condition mismatch for {name}: GetPointer='{gp_condition}', "
                                f"AddSpec='{addspec_condition}'"
                            )
                    elif gp_condition and not addspec_condition:
                        self.logger.warning(
                            f"Condition in GetPointer but not AddSpec for {name}: '{gp_condition}'"
                        )
                    
                    # Add alloc if present
                    if 'alloc' in getpointer_data[gp_key]:
                        field['ALLOC'] = 'T' if getpointer_data[gp_key]['alloc'] else 'F'
                else:
                    self.logger.warning(f"Field {name} in {category.value} not found in GetPointer file")
                
                # Check for missing mandatory fields
                for mandatory_col in MANDATORY_COLUMNS_BASE:
                    if mandatory_col not in field:
                        self.logger.error(f"Missing mandatory field {mandatory_col} for {name}")
                        field[mandatory_col] = MISSING_VALUE
                
                merged_fields.append(field)
            
            merged_data[category] = merged_fields
        
        # Check for orphaned fields in DeclarePointer or GetPointer
        for name in declare_data:
            # Check if this name appears in any category in addspec
            if not any((name, cat) in addspec_fields for cat in ['import', 'export', 'internal']):
                self.logger.warning(f"Field {name} in DeclarePointer but not in AddSpec files")
        
        for (name, cat) in getpointer_data:
            if (name, cat) not in addspec_fields:
                self.logger.warning(f"Field {name} ({cat}) in GetPointer but not in AddSpec files")
        
        return merged_data
    
    def compute_rank(self, dims: str, ungridded: Optional[str] = None) -> int:
        """Compute expected rank from DIMS and UNGRIDDED_DIMS"""
        dims_rank = DIMS_TO_RANK.get(dims, 0)
        
        if not ungridded:
            return dims_rank
        
        # Count commas in ungridded to get number of dimensions
        ungridded_rank = ungridded.count(',') + 1 if ungridded.strip() else 0
        
        return dims_rank + ungridded_rank

######################## ACG SPEC GENERATOR ####################################

class ACGSpecGenerator:
    """Generates ACG spec file from merged field data"""
    
    def __init__(self, schema_version: str, component: str, logger: Logger):
        self.schema_version = schema_version
        self.component = component
        self.logger = logger
    
    def generate(self, merged_data: Dict[Category, List[Dict]], output_path: Path):
        """Generate and write ACG spec file"""
        try:
            with open(output_path, 'w') as f:
                # Write header
                f.write(f"schema_version: {self.schema_version}\n")
                f.write(f"component: {self.component}\n")
                
                # Write each category
                for i, (category, fields) in enumerate(merged_data.items()):
                    if not fields:
                        continue
                    
                    # Blank line before category
                    f.write("\n")
                    
                    # Write category header
                    f.write(f"category: {category.value}\n")
                    
                    # Determine columns for this category
                    columns = self.determine_columns(fields)
                    
                    # Compute column widths
                    widths = self.compute_column_widths(fields, columns)
                    
                    # Write comment separator
                    separator = self.generate_comment_separator(widths, columns)
                    f.write(separator + "\n")
                    
                    # Write metadata comment
                    f.write("#  VARIABLE")
                    f.write(" " * (widths['NAME'] - len("VARIABLE")))
                    f.write(" | DIMENSIONS")
                    # Calculate remaining space
                    dims_section_width = widths['UNITS'] + widths['DIMS'] + widths['VLOC'] + 6  # 6 for pipes and spaces
                    f.write(" " * (dims_section_width - len("DIMENSIONS")))
                    f.write(" | Additional Metadata\n")
                    
                    # Write comment separator
                    f.write(separator + "\n")
                    
                    # Write column headers
                    header_parts = []
                    for col in columns:
                        header_parts.append(col.ljust(widths[col]))
                    f.write(" | ".join(header_parts) + "\n")
                    
                    # Write comment separator
                    f.write(separator + "\n")
                    
                    # Write data rows
                    for field in fields:
                        row = self.format_row(field, columns, widths)
                        f.write(row + "\n")
            
            self.logger.info(f"Successfully generated ACG spec file: {output_path}")
            
        except Exception as e:
            self.logger.error(f"Error writing ACG spec file: {e}")
            raise
    
    def determine_columns(self, fields: List[Dict]) -> List[str]:
        """Determine which columns to include"""
        # Start with mandatory columns
        columns = []
        
        # NAME always first
        columns.append('NAME')
        
        # Other mandatory columns (except LONG_NAME which goes last)
        for col in MANDATORY_COLUMNS_BASE:
            if col not in ['NAME', 'LONG_NAME']:
                columns.append(col)
        
        # Check optional columns
        for col in OPTIONAL_COLUMNS:
            # Include if any field has a non-empty value
            if any(field.get(col) for field in fields):
                columns.append(col)
        
        # LONG_NAME always last
        if any('LONG_NAME' in field for field in fields):
            columns.append('LONG_NAME')
        
        return columns
    
    def compute_column_widths(self, fields: List[Dict], columns: List[str]) -> Dict[str, int]:
        """Compute width for each column to align pipes"""
        widths = {}
        
        for col in columns:
            # Start with column name length
            max_width = len(col)
            
            # Check all field values
            for field in fields:
                value = field.get(col, '')
                if value:
                    max_width = max(max_width, len(str(value)))
            
            # Add padding
            widths[col] = max_width + 1
        
        return widths
    
    def format_row(self, field: Dict, columns: List[str], widths: Dict[str, int]) -> str:
        """Format a data row with aligned pipes"""
        parts = []
        
        for col in columns:
            value = field.get(col, '')
            if value is None:
                value = ''
            parts.append(str(value).ljust(widths[col]))
        
        return " | ".join(parts)
    
    def generate_comment_separator(self, widths: Dict[str, int], columns: List[str]) -> str:
        """Generate comment line with dashes"""
        # Calculate total width of row
        total_width = sum(widths.values()) + len(columns) * 3 - 3  # Account for " | " separators
        return "#" + "-" * (total_width + 1)

################################### MAIN #######################################

def main():
    """Main function"""
    
    # Parse command-line arguments
    parser = argparse.ArgumentParser(
        description='Convert MAPL include files back to ACG spec file',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Example usage:
  %(prog)s ACG_Import___.h ACG_Export___.h ACG_DeclarePointer___.h -o ACG_StateSpecs.rc
  %(prog)s *.h --component Ocean --schema 2.0.0
        """
    )
    
    parser.add_argument('files', nargs='+', metavar='FILE',
                        help='Include files (.h) and optional Fortran source files (.F90)')
    parser.add_argument('-o', '--output', metavar='FILE',
                        help='Output ACG spec file (default: {component}_StateSpecs.rc)')
    parser.add_argument('--component', metavar='NAME',
                        help='Component name (extracted from files if not provided)')
    parser.add_argument('--schema', metavar='VERSION', default=SCHEMA_VERSION_DEFAULT,
                        help=f'Schema version (default: {SCHEMA_VERSION_DEFAULT})')
    parser.add_argument('--log', metavar='FILE', default=LOG_FILE_DEFAULT,
                        help=f'Error log file (default: {LOG_FILE_DEFAULT})')
    
    args = parser.parse_args()
    
    # Initialize logger
    logger = Logger(Path(args.log))
    logger.info("MAPL_IncludeFiles_to_ACG.py started")
    logger.info(f"Input files: {args.files}")
    
    try:
        # Detect file types
        detector = FileTypeDetector()
        file_types = {}
        
        for filepath_str in args.files:
            filepath = Path(filepath_str)
            if not filepath.exists():
                logger.error(f"File not found: {filepath}")
                continue
            
            file_type = detector.detect(filepath, logger)
            file_types[filepath] = file_type
            logger.info(f"Detected {filepath.name}: {file_type.value}")
        
        # Check for required file types
        has_addspec = any(ft in [FileType.ADD_IMPORT, FileType.ADD_EXPORT, FileType.ADD_INTERNAL] 
                         for ft in file_types.values())
        has_declare = FileType.DECLARE_POINTER in file_types.values()
        has_get = FileType.GET_POINTER in file_types.values()
        
        if not has_addspec:
            logger.error("No AddSpec files found. At least one AddSpec file is required.", fatal=True)
            logger.close()
            sys.exit(-1)
        
        if not has_declare:
            logger.warning("No DeclarePointer file found")
        
        if not has_get:
            logger.warning("No GetPointer file found")
        
        # Parse files
        declare_data = {}
        getpointer_data = {}
        addspec_data = {Category.IMPORT: [], Category.EXPORT: [], Category.INTERNAL: []}
        
        for filepath, file_type in file_types.items():
            if file_type == FileType.DECLARE_POINTER:
                parser_obj = DeclarePointerParser(logger)
                declare_data = parser_obj.parse(filepath)
                
            elif file_type == FileType.GET_POINTER:
                parser_obj = GetPointerParser(logger)
                getpointer_data = parser_obj.parse(filepath)
                
            elif file_type == FileType.ADD_IMPORT:
                parser_obj = AddSpecParser(logger)
                addspec_data[Category.IMPORT] = parser_obj.parse(filepath, Category.IMPORT)
                
            elif file_type == FileType.ADD_EXPORT:
                parser_obj = AddSpecParser(logger)
                addspec_data[Category.EXPORT] = parser_obj.parse(filepath, Category.EXPORT)
                
            elif file_type == FileType.ADD_INTERNAL:
                parser_obj = AddSpecParser(logger)
                addspec_data[Category.INTERNAL] = parser_obj.parse(filepath, Category.INTERNAL)
        
        # Extract component name
        extractor = ComponentNameExtractor(logger)
        component = extractor.extract(args.component, [Path(f) for f in args.files])
        
        # Merge field data
        merger = FieldDataMerger(logger)
        merged_data = merger.merge(addspec_data, declare_data, getpointer_data)
        
        # Determine output filename
        if args.output:
            output_path = Path(args.output)
        else:
            output_path = Path(f"{component}_StateSpecs.rc")
        
        # Generate ACG spec file
        generator = ACGSpecGenerator(args.schema, component, logger)
        generator.generate(merged_data, output_path)
        
        print(f"Generated ACG spec file: {output_path}")
        
    except Exception as e:
        logger.error(f"Fatal error: {str(e)}")
        import traceback
        logger.error(traceback.format_exc())
        logger.close()
        # Exit with -1 for fatal errors
        sys.exit(-1)
        
    finally:
        logger.close()
    
    # Exit codes:
    # 0 = success (no errors)
    # positive number = count of non-fatal errors
    # -1 = fatal error (handled in except block above)
    sys.exit(logger.error_count if logger.error_count > 0 else 0)

if __name__ == "__main__":
    main()
